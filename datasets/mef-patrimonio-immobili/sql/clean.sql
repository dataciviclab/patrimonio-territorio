SELECT
    {year}::INTEGER AS anno,
    normalize_string("Settore Istituzionale") AS settore_istituzionale,
    normalize_string("Macrocategoria Amministrazione") AS macrocategoria_amministrazione,
    normalize_string("Tipologia Amministrazione") AS tipologia_amministrazione,
    normalize_string("Amministrazione Denominazione") AS amministrazione_denominazione,
    normalize_string(REPLACE(REPLACE("Amministrazione Codice Fiscale", '[', ''), ']', '')) AS amministrazione_codice_fiscale,
    normalize_string("Regione (Amministrazione)") AS reg_amministrazione,
    normalize_string("Provincia (Amministrazione)") AS prov_amministrazione,
    normalize_string("Comune (Amministrazione)") AS comune_amministrazione,
    normalize_string("Cod. Comune (Amministrazione)") AS codice_comune_amministrazione,
    normalize_string("Titolo proprietà") AS titolo_proprieta,
    cast_double("Quota proprietà") AS quota_proprieta,
    normalize_string("Titolo detenzione") AS titolo_detenzione,
    decode_flag("Detenzione Intera UI", 'Sì') AS detenzione_intera_ui,
    cast_double("Superficie in detenzione") AS superficie_detenzione_mq,
    cast_double(remove_dot_thousands("Canone annuale")) AS canone_annuale,
    normalize_string("Sogg. cedente (denominazione)") AS soggetto_cedente,
    normalize_string("Soggetto cedente (CF)") AS soggetto_cedente_cf,
    cast_bigint("ID bene") AS id_bene,
    normalize_string("Natura del bene") AS natura_bene,
    normalize_string("Stato Accatastamento") AS stato_accatastamento,
    normalize_string("Sistema Catastale") AS sistema_catastale,
    normalize_string("Regione del bene") AS regione_bene,
    normalize_string("Provincia del bene") AS provincia_bene,
    normalize_string("Comune del bene") AS comune_bene,
    normalize_string("Codice Comune del bene") AS codice_comune_bene,
    normalize_string("Indirizzo") AS indirizzo,
    normalize_string("Numero Civico") AS numero_civico,
    normalize_string("Fonte Georeferenziazione") AS fonte_georef,
    normalize_string("Precisione Georeferenziazione") AS precisione_georef,
    decode_flag("Immobile Geo-Ref.", 'Si') AS immobile_georef,
    cast_double("Latitudine") AS latitudine,
    cast_double("Longitudine") AS longitudine,
    normalize_string("Identificativo catastale") AS identificativo_catastale,
    normalize_string("Codice Bene non accatastato") AS codice_bene_non_accatastato,
    normalize_string("Tipologia Bene Immobile") AS tipologia_bene,
    cast_double("Superficie (mq)") AS superficie_mq,
    cast_double("Cubatura (mc)") AS cubatura_mc,
    cast_double("Sup. aree pertinenziali (mq)") AS sup_aree_pertinenziali_mq,
    cast_double("Superficie di Riferimento (mq)") AS superficie_riferimento_mq,
    normalize_string("Epoca Costruzione") AS epoca_costruzione,
    normalize_string("Vinc. culturale/paesaggistico") AS vincoli,
    normalize_string("Natura Giuridica del Bene") AS natura_giuridica_bene,
    normalize_string("Diritto gravante sul terreno") AS diritto_gravante_terreno,
    cast_bigint("ID Compendio") AS id_compendio,
    normalize_string("Descrizione Compendio") AS descrizione_compendio,
    normalize_string("Tipologia Compendio") AS tipologia_compendio,
    normalize_string("Utilizzo del bene") AS utilizzo_bene,
    normalize_string("Finalità") AS finalita,
    normalize_string("Altra finalità") AS altra_finalita,
    decode_flag("ui data interamente a terzi", 'Si') AS ui_data_interamente_terzi,
    decode_flag("ui data parzialmente a terzi", 'Si') AS ui_data_parzialmente_terzi
FROM raw_input
